import assert from "node:assert/strict";
import { trackingRefreshFinished as done } from "./trackingRefreshPolicy.js";
assert(done({ vendorStatus: " Complete ", tracking: [] }));
assert(done({ vendorStatus: "Complete, Completed" }));
assert(!done({ vendorStatus: "Complete, Processing" }));
assert(!done({ tracking: [] }));
assert(!done({ tracking: [{ carrierStatus: "DELIVERED" }, { carrierStatus: "TRANSIT" }] }));
assert(done({ tracking: [{ carrierStatus: "DELIVERED" }] }));
assert(!done({ tracking: [{}] }));
const rows = [...Array.from({ length: 18 }, () => ({ vendorStatus: "Complete" })), { vendorStatus: "Processing" }];
assert.equal(rows.filter(x => !done(x)).length, 1);
console.log("8 refresh eligibility checks passed");
